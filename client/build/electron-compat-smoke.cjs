const { app, BrowserWindow, Menu } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'xiquan-electron-smoke-'))
app.setPath('userData', temporary)
app.whenReady().then(async () => {
  const updater = require('../electron/updater.cjs')
  assert.equal(updater.getStartupError(), '')
  assert.equal(updater.getState().status, 'disabled')
  const { ElectronHttpExecutor } = require('electron-updater/out/electronHttpExecutor')
  const Pinned = require('../electron/update-executor.cjs').createPinnedExecutorClass(ElectronHttpExecutor)
  const executor = new Pinned({ origin: 'https://api.pqxqxy.xyz', feedPath: '/updates/desktop/win7-x86/' })
  assert.equal(executor.maxRedirects, 0)
  assert.throws(() => executor.createRequest({ protocol: 'http:', hostname: 'example.invalid', path: '/' }, () => {}))
  Menu.buildFromTemplate(require('../electron/security.cjs').menuTemplate(false))
  const win = new BrowserWindow({ show: false, webPreferences: { sandbox: true, contextIsolation: true,
    nodeIntegration: false, preload: path.resolve(__dirname, '../electron/preload.cjs') } })
  await win.loadURL('data:text/html,<html><body>isolated smoke</body></html>')
  const bridge = await win.webContents.executeJavaScript('({present:typeof window.xiquan === "object",diagnostics:typeof window.xiquan?.getDesktopDiagnostics,print:typeof window.xiquan?.getPrinters})')
  assert.equal(bridge.present, true); assert.equal(bridge.diagnostics, 'function'); assert.equal(bridge.print, 'function')
  const assetRoot = path.resolve(__dirname, '../dist/assets')
  const assets = fs.readdirSync(assetRoot)
  const paymentCss = fs.readFileSync(path.join(assetRoot, assets.find(name => /^MemberRechargeView-.*\.css$/.test(name))), 'utf8')
  const globalCss = fs.readFileSync(path.join(assetRoot, assets.find(name => /^index-.*\.css$/.test(name))), 'utf8')
  const attributes = [...new Set((paymentCss.match(/\[data-v-[a-f0-9]+\]/g) || []).map(value => value.slice(1, -1)))].join(' ')
  await win.loadURL('data:text/html;charset=utf-8,' + encodeURIComponent(`<html><head><style>${globalCss}\n${paymentCss}</style></head><body><div id="app"><div class="method-list"><button class="active" style="--method-color:#26a778" ${attributes}><i ${attributes}></i><strong ${attributes}>现金</strong></button></div></div></body></html>`))
  const styles = await win.webContents.executeJavaScript('({background:getComputedStyle(document.querySelector("button")).backgroundColor,shadow:getComputedStyle(document.querySelector("i")).boxShadow,minWidth:getComputedStyle(document.documentElement).minWidth})')
  assert.notEqual(styles.background, 'rgba(0, 0, 0, 0)'); assert.notEqual(styles.background, 'rgb(255, 255, 255)')
  assert.notEqual(styles.shadow, 'none'); assert.equal(styles.minWidth, '0px')
  win.destroy()
  console.log(JSON.stringify({ passed: true, electron: process.versions.electron, node: process.versions.node,
    chromium: process.versions.chrome, arch: process.arch, bridge: true, sandbox: true, styles, network: false, installed: false }))
  app.exit(0)
}).catch(error => { console.error(error.message); app.exit(1) })
